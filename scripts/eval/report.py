"""
eval/report.py
==============
Generates reports for Eval Runs
"""

import json
import logging
from pathlib import Path

from .config import EVAL_RUNS_DIR, PROJECT_ROOT

logger = logging.getLogger(__name__)

DOCS_BENCHMARKS_DIR = PROJECT_ROOT / "docs" / "benchmarks"


def generate_markdown_report(run_id: str, results: dict) -> Path:
    """Converts the eval JSON results into a readable Markdown table."""
    DOCS_BENCHMARKS_DIR.mkdir(parents=True, exist_ok=True)
    report_path = DOCS_BENCHMARKS_DIR / f"{run_id}.md"

    lines = [
        f"# Evaluation Benchmark: {run_id}",
        "This report was automatically generated by the DeepVault Evaluation Engine.",
        "",
        "## Overall Leaderboard",
        "| Strategy (Chunking + Retrieval) | Hit Rate | MRR | Precision | P50 Latency (ms) | P95 Latency (ms) | Answer Correctness | Faithfulness | Context Precision |",
        "|---|---|---|---|---|---|---|---|---|",
    ]

    # Sort strategies by a combined score of Hit Rate + Answer Correctness
    sorted_combos = []
    for combo, data in results.items():
        ret = data.get("custom_retrieval", {})
        ragas = data.get("ragas", {})

        hit_rate = ret.get("hit_rate", 0)
        mrr = ret.get("mrr", 0)
        precision = ret.get("precision", 0)
        p50 = ret.get("latency_p50_ms", 0)
        p95 = ret.get("latency_p95_ms", 0)

        # Ragas metrics can sometimes be null if they fail to parse
        correctness = ragas.get("answer_correctness") or 0.0
        faithfulness = ragas.get("faithfulness") or 0.0
        context_precision = ragas.get("context_precision") or 0.0

        score = hit_rate + correctness

        sorted_combos.append(
            {
                "combo": combo,
                "score": score,
                "hit_rate": hit_rate,
                "mrr": mrr,
                "precision": precision,
                "p50": p50,
                "p95": p95,
                "correctness": correctness,
                "faithfulness": faithfulness,
                "context_precision": context_precision,
            }
        )

    sorted_combos.sort(key=lambda x: x["score"], reverse=True)

    for row in sorted_combos:
        c = row
        lines.append(
            f"| `{c['combo']}` | {c['hit_rate']:.2f} | {c['mrr']:.2f} | {c['precision']:.2f} | {c['p50']:.1f} | {c['p95']:.1f} | {c['correctness']:.2f} | {c['faithfulness']:.2f} | {c['context_precision']:.2f} |"
        )

    if sorted_combos:
        lines.insert(3, f"**🏆 Winner:** `{sorted_combos[0]['combo']}`")

    with open(report_path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))

    logger.info(f"Generated Markdown report at {report_path}")
    return report_path


def save_report(run_id: str, results: dict):
    """Saves the JSON results to disk and generates the markdown report."""
    run_dir = EVAL_RUNS_DIR / run_id
    run_dir.mkdir(parents=True, exist_ok=True)

    json_path = run_dir / "summary.json"
    with open(json_path, "w", encoding="utf-8") as f:
        json.dump(results, f, indent=2)

    logger.info(f"Saved evaluation JSON report to {json_path}")

    # Also generate the markdown report
    generate_markdown_report(run_id, results)

    return json_path
